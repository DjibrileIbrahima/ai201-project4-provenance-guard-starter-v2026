"""
Turning two numbers into one, and one number into something a person can read.

Two functions live here, and both are stubs.

`combine_signals` is where your false-positive decision from Milestone 1
actually gets made. Everything above it — the labels, the appeal path — is
downstream of a number this function produced.

`score_to_label` is where you stop writing for a machine and start writing for
a person. A score of 0.62 means nothing to a writer.

⚠️ Your README's **Signals and Scoring** section has to name the file and
function holding your combining rule. The grader checks your code against what
you claim, so that line should read `scoring.py::combine_signals`.
"""

import config


def combine_signals(model_score: float, style_score: float) -> float:
    """
    Combine two 0-1 signals into one 0-1 score. Higher = more likely AI.

    The rule:

      1. Start from an equal-weighted average of the two signals
         (WEIGHT_MODEL_SIGNAL = WEIGHT_STYLE_SIGNAL = 0.5). Neither signal earns
         more trust: the model signal accuses plain writers, the style signal
         is fooled by anything that changes the shape of the text.

      2. If the two signals are DISAGREEMENT_GAP (0.4) or more apart, cap the
         result just below AI_THRESHOLD. Two methods flatly disagreeing is
         uncertainty, and uncertainty is never enough to accuse someone. The
         cap only works downward: disagreement can still land on "human".

    This leans toward being wrong in the human direction on purpose. A missed
    AI text costs the site a little; a wrong accusation costs a writer a lot.
    """
    score = (
        config.WEIGHT_MODEL_SIGNAL * model_score
        + config.WEIGHT_STYLE_SIGNAL * style_score
    )
    if abs(model_score - style_score) >= config.DISAGREEMENT_GAP:
        score = min(score, config.AI_THRESHOLD - 0.01)
    return round(min(max(score, 0.0), 1.0), 4)


LABEL_HUMAN = (
    "This reads like it was written by a person. Nothing in it suggests it was "
    "generated by AI."
)
LABEL_UNSURE = (
    "We can't tell either way. Our checks gave mixed or middling results, which "
    "happens a lot with genuine human writing, so this is not a finding that "
    "AI was used. Nothing has been flagged, and no one will act on this result "
    "alone."
)
LABEL_AI = (
    "Our checks found strong signs that this may have been generated by AI. "
    "This is an automated estimate, not proof, and it can be wrong, especially "
    "for plain or simple writing. If you wrote this yourself, you can appeal "
    "and a person will review it."
)


def score_to_label(score: float) -> tuple[str, str]:
    """
    Turn a score into (guess, label_text).

        score <  HUMAN_THRESHOLD (0.40)   -> "human"
        HUMAN_THRESHOLD <= score < AI_THRESHOLD (0.75) -> "unsure"
        score >= AI_THRESHOLD             -> "ai"

    The ranges share their edges, so there is no gap: every score from 0.0 to
    1.0 gets exactly one label.
    """
    if score >= config.AI_THRESHOLD:
        return "ai", LABEL_AI
    if score < config.HUMAN_THRESHOLD:
        return "human", LABEL_HUMAN
    return "unsure", LABEL_UNSURE


def label_ranges() -> list[tuple[str, str]]:
    """
    The score range each label covers. Your README needs these beside the
    label text — given to you so the numbers can't drift apart from config.py.
    """
    return [
        ("high-confidence human", f"0.00 – {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} – {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} – 1.00"),
    ]
